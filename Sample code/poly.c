/* poly.c — CMSC 132 · Data-Level Parallelism lab (Tasks 0-3)
 *
 * The loop under study is an elementwise MAP: for each element we evaluate
 * the same degree-15 polynomial.
 *
 *        y[i] = P(x[i])          (Horner form, 15 multiply-adds)
 *
 * Every iteration is INDEPENDENT (y[i] depends only on x[i]), and each does
 * a chunk of real arithmetic. That makes it a textbook target for SIMD: the
 * compiler can evaluate the polynomial for several elements AT ONCE, one per
 * vector lane. (We use a compute-heavy map on purpose; a trivial loop like
 * y[i]=a*x[i]+y[i] is limited by memory bandwidth, not by the vector width,
 * so it would hide the effect this lab is about.)
 *
 * You normally do NOT edit this file, with ONE exception for Task 3:
 * change the data type on the line marked  <<< TASK 3 >>>  from
 * `float` to `double` and rebuild.
 *
 * Build it two ways (see the Makefile):
 *     make scalar     # SIMD disabled  -> one element per instruction
 *     make vector     # SIMD enabled   -> many elements per instruction
 *
 * Run:  ./scalar      and      ./vector
 *       ./vector 4000000 9        # optional: N elements, odd #repetitions
 */

#include <stdio.h>
#include <stdlib.h>
#include "timer.h"

/* ----------------------------------------------------------------------
 * <<< TASK 3 >>>  Change `float` to `double` here (one edit) and rebuild.
 * A 128-bit NEON register holds 4 floats but only 2 doubles; a 256-bit AVX
 * register holds 8 floats but only 4 doubles. Fewer lanes -> less speedup.
 * Predict the change, THEN measure.
 * -------------------------------------------------------------------- */
typedef float real;

/* The kernel. `restrict` promises x and y don't overlap, which lets the
 * compiler vectorize the loop. Keeping it in its own function makes it easy
 * to find in the vectorizer report and in the assembly. */
void poly(long n, const real *restrict x, real *restrict y) {
    for (long i = 0; i < n; i++) {
        real t = x[i];
        real r = (real)0.1;                 /* degree-15 polynomial, Horner */
        r = r*t + (real)0.2;  r = r*t + (real)0.3;  r = r*t + (real)0.4;
        r = r*t + (real)0.5;  r = r*t + (real)0.6;  r = r*t + (real)0.7;
        r = r*t + (real)0.8;  r = r*t + (real)0.9;  r = r*t + (real)1.0;
        r = r*t + (real)1.1;  r = r*t + (real)1.2;  r = r*t + (real)1.3;
        r = r*t + (real)1.4;  r = r*t + (real)1.5;  r = r*t + (real)1.6;
        y[i] = r;
    }
}

int main(int argc, char **argv) {
    long n    = (argc > 1) ? atol(argv[1]) : 8L * 1024 * 1024;  /* 8M */
    int  reps = (argc > 2) ? atoi(argv[2]) : 30;

    real *x = malloc((size_t)n * sizeof(real));
    real *y = malloc((size_t)n * sizeof(real));
    if (!x || !y) { fprintf(stderr, "allocation failed\n"); return 1; }

    /* Deterministic input so the checksum is reproducible across builds. */
    for (long i = 0; i < n; i++) x[i] = (real)((i & 15) * 0.01);

    poly(n, x, y);  /* warm-up run (touch pages, fill caches) — not timed */

    /* We report the FASTEST run. The kernel always does the same work, so
     * slower runs only mean the OS stole the core mid-measurement; the
     * minimum is the cleanest estimate of the kernel's real speed. */
    double best_ms = 1e30;
    for (int r = 0; r < reps; r++) {
        double t0 = now_sec();
        poly(n, x, y);
        double ms = (now_sec() - t0) * 1000.0;
        if (ms < best_ms) best_ms = ms;
    }

    /* Consume y so the optimizer can't delete the loop, and so you can
     * confirm scalar and vector produce the SAME result. */
    double checksum = 0.0;
    for (long i = 0; i < n; i++) checksum += (double)y[i];

    printf("N = %ld elements (type = %zu B)\n", n, sizeof(real));
    printf("best time : %.3f ms   (fastest of %d reps)\n", best_ms, reps);
    printf("checksum  : %.3f   <-- must match between scalar and vector\n",
           checksum);

    free(x); free(y);
    return 0;
}
